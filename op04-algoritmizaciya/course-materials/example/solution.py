"""Пример оформления решения: максимум последовательности за один проход.

Задача. Дан список целых чисел. Вернуть наибольшее из них.
Если список пуст, ответа не существует — возвращаем None.
"""


def max_value(numbers):
    """Возвращает максимум списка или None для пустого входа.

    Инвариант: перед каждой итерацией в best лежит максимум уже
    просмотренной части списка. После последней итерации просмотрен весь
    список, значит в best максимум всей последовательности.
    """
    if not numbers:
        return None

    best = numbers[0]
    for value in numbers[1:]:
        if value > best:
            best = value
    return best


if __name__ == "__main__":
    print(max_value([7, 2, 9, 2]))
