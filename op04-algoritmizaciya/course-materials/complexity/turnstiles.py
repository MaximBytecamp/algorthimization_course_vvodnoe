"""Короткая практика: ускорить решение, не меняя ответа · занятие 3.

Турникеты на стадионе пишут в журнал номер билета при каждом проходе.
Нужно узнать, сколько билетов прошли больше одного раза.

Решение ниже работает правильно. Проверьте это: запустите файл, ответ
должен быть 2 — билеты A-118 и C-004.

Задание на шесть минут:

1. Посчитайте, сколько сравнений сделает count_reused при n проходах.
   Считайте худший случай: все номера разные.
2. Перепишите функцию так, чтобы ответ остался прежним, а число сравнений
   росло не быстрее n. Менять разрешается любые строки внутри функции.
3. Докажите, что стало быстрее: допишите счётчик и сравните числа
   на журналах из 100 и 200 проходов. Печатать секунды не нужно.

Заготовка для счётчика уже стоит: увеличивайте comparisons там, где
происходит сравнение номеров.
"""

LOG = ["A-118", "B-207", "A-118", "C-004", "D-091", "C-004", "E-330"]


def count_reused(log):
    """Возвращает, сколько номеров встречаются в журнале больше одного раза."""
    reused = []
    for i in range(len(log)):
        for j in range(i + 1, len(log)):
            if log[i] == log[j] and log[i] not in reused:
                reused.append(log[i])
    return len(reused)


def make_log(size):
    """Журнал из size разных номеров — худший вход: повторов нет."""
    return [f"T-{number:05d}" for number in range(size)]


if __name__ == "__main__":
    print("ответ на учебном журнале:", count_reused(LOG))
    print("проходов в журнале:", len(make_log(100)))
