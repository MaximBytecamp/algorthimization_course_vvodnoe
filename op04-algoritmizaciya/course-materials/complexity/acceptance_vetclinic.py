"""Приёмка занятия 3: чужой код, незнакомая задача.

Ветклиника ведёт журнал приёмов: для каждого визита записаны час начала
и порода. Функция busiest_hour отвечает, в какой час было больше всего
приёмов и сколько разных пород пришло в этот час.

Код рабочий, менять его не нужно. Ответьте на четыре вопроса — письменно,
в lesson_03/acceptance.md:

1. T(n) — как растёт число операций с ростом числа визитов. Назовите,
   какие именно операции вы считали.
2. S(n) — сколько памяти функция занимает дополнительно ко входу.
3. Худший случай: при каком журнале работы больше всего и почему.
4. Одна строка кода делает больше работы, чем кажется по её виду.
   Найдите её и скажите, сколько операций за ней стоит.

Засчитывается ответ, в котором названы операции, а не только буква
в скобках. «O(n log n)» без объяснения — это угадывание.
"""


def busiest_hour(visits):
    """Возвращает (час, число приёмов, число разных пород) или None.

    visits — список пар (час, порода): [(9, "кошка"), (9, "такса"), ...]
    """
    if not visits:
        return None

    by_hour = {}
    for hour, breed in visits:
        if hour not in by_hour:
            by_hour[hour] = []
        by_hour[hour].append(breed)

    ordered = sorted(by_hour.items(), key=lambda pair: len(pair[1]), reverse=True)
    best_hour, breeds = ordered[0]

    distinct = 0
    counted = set()
    for breed in breeds:
        if breed not in counted:
            counted.add(breed)
            distinct += 1

    return best_hour, len(breeds), distinct


