def count_cheap_pairs(prices, limit):
    """Сколько пар товаров i < j стоят вместе строго меньше limit.

    prices отсортированы по возрастанию. Время O(n), память O(1).
    """
    i, j = 0, len(prices) - 1
    count = 0
    while i < j:
        if prices[i] + prices[j] <= limit:
            # prices[i] с любой ценой от i + 1 до j тоже дешевле limit:
            # это j - i пар, все они засчитываются сразу
            count += j - i
            i += 1
        else:
            j -= 1
    return count


def dedup_keep_two(ids):
    """Оставляет каждое значение отсортированного списка не больше двух раз.

    Изменяет список на месте, возвращает новую длину. Время O(n), память O(1).
    """
    w = 2
    for r in range(2, len(ids)):
        if ids[r] != ids[w - 2]:
            ids[w] = ids[r]
            w += 1
    del ids[w:]
    return w


def is_mirror(chars):
    """True, если список символов читается одинаково слева направо и справа налево.

    Время O(n), память O(1).
    """
    i, j = 0, len(chars) - 1
    while i < j - 1:
        if chars[i] != chars[j]:
            return False
        i += 1
        j -= 1
    return True
