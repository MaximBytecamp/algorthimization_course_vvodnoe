"""Предусловие и постусловие, записанные проверками.

assert — это утверждение, которое должно быть истинным в этой точке.
Если оно ложно, программа останавливается и печатает сообщение.
"""


def srednee(chisla):
    """Среднее арифметическое непустого списка чисел.

    Предусловие: список непустой.
    Постусловие: ответ не меньше минимума и не больше максимума списка.
    """
    assert len(chisla) > 0, 'предусловие: список не должен быть пустым'
    itog = sum(chisla) / len(chisla)
    assert min(chisla) <= itog <= max(chisla), 'постусловие: среднее вне диапазона'
    return itog


print('srednee([4, 6]) =', srednee([4, 6]))
print('srednee([-5, 5]) =', srednee([-5, 5]))
print('srednee([]) — вызов с нарушенным предусловием:')
srednee([])
