def shape(tok):
    t = tok.strip('"\'')
    notes = []
    if t == '/': notes.append('корневой каталог')
    elif t == '..': notes.append('каталог уровнем выше')
    elif t == '.': notes.append('текущий каталог')
    elif t == '~': notes.append('домашний каталог')
    elif t.startswith('~/'): notes.append('путь от домашнего каталога')
    elif t.startswith('$HOME'): notes.append('путь от домашнего каталога: $HOME заменяется на /home/ubuntu')
    elif t.startswith('/'): notes.append('абсолютный путь')
    elif '/' in t or '.' in t: notes.append('путь относительно текущего каталога')
    if '{' in t: notes.append('фигурные скобки: оболочка превратит запись в несколько путей')
    if '*' in t: notes.append('звёздочка заменяет любые символы')
    if '$$' in t: notes.append('$$ — номер процесса текущей оболочки')
    if '\\n' in t: notes.append('\\n — перевод строки')
    if '%s' in t: notes.append('%s — место, куда подставится значение')
    return '; '.join(notes)


def explain(cmdline):
    lex = shlex.shlex(cmdline, posix=False)
    lex.whitespace_split = True
    lex.commenters = ''
    tokens = list(lex)
    parts, i, cmd, argn = [], 0, None, 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in OPS:
            parts.append((tok, OPS[tok])); cmd = None; i += 1
            if tok in ('>', '>>') and i < len(tokens):
                parts.append((tokens[i], 'файл, в который записывается вывод')); i += 1
            continue
        if cmd is None:
            cmd, argn = tok, 0
            text = CMD.get(tok, '')
            if tok == 'cat' and parts and parts[-1][0] == '|' and i + 1 == len(tokens):
                text = 'вывести полученный текст как есть; findmnt тогда печатает простой список без рамок дерева'
            parts.append((tok, text))
            i += 1
            if cmd == 'sudo':
                cmd = None
            continue
        if tok.startswith('-') and not tok.lstrip('-').isdigit() or (cmd == 'head' and tok.startswith('-')):
            if cmd == 'head':
                parts.append((tok, FLAG[('head', '-N')].format(v=tok[1:]))); i += 1; continue
            if not tok.startswith('--') and len(tok) > 2 and cmd in SPLIT_SHORT:
                for ch in tok[1:]:
                    parts.append((f'-{ch}', FLAG.get((cmd, f'-{ch}'), '')))
                i += 1; continue
            if (cmd, tok) in VALUE_FLAGS and i + 1 < len(tokens):
                v = tokens[i + 1]
                text = FLAG.get((cmd, tok, v)) or FLAG.get((cmd, tok), '').format(v=v)
                parts.append((f'{tok} {v}', text)); i += 2; continue
            parts.append((tok, FLAG.get((cmd, tok), ''))); i += 1; continue
        roles = ROLE.get(cmd, [''])
        role = roles[min(argn, len(roles) - 1)]
        argn += 1
        text = SPECIAL.get((cmd, tok))
        if not text:
            s = shape(tok)
            text = f'{role} ({s})' if role and s else (role or s)
        parts.append((tok, text))
        i += 1
    for p, t in parts:
        if not t:
            UNKNOWN.append(f'{cmdline!r} → {p}')
    return parts
