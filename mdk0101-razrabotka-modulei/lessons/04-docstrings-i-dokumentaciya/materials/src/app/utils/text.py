"""Работа с именами официантов."""


def _squash_spaces(value: str) -> str:
    """Заменяет подряд идущие пробелы одним."""
    return " ".join(value.split())


def normalize_name(name: str) -> str:
    """Приводит имя официанта к виду «Фамилия Имя».

    Лишние пробелы убираются, каждое слово начинается с заглавной буквы.
    Имена в файле записаны по-разному, а группировка заказов идёт по
    совпадению строк, поэтому вызывать эту функцию нужно сразу при чтении
    данных.

    Args:
        name: Имя в произвольном виде, например «  иванов   пётр ».

    Returns:
        Имя вида «Иванов Пётр».
    """
    return _squash_spaces(name).title()
