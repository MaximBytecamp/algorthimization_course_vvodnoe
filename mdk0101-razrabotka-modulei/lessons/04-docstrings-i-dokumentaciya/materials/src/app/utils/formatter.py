"""Форматирование сумм и заголовков отчёта."""


def format_kopeks(kopeks: int) -> str:
    """Переводит сумму в копейках в строку с рублями.

    Args:
        kopeks: Сумма в копейках, неотрицательная.

    Returns:
        Строка вида «1 250,00 ₽»: пробел разделяет тысячи, запятая
        отделяет копейки.

    Examples:
        >>> format_kopeks(125000)
        '1 250,00 ₽'
        >>> format_kopeks(0)
        '0,00 ₽'
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Центрирует заголовок отчёта, достраивая строку знаками «=».

    Args:
        text: Текст заголовка без пробелов по краям.
        width: Итоговая ширина строки в знаках. Значение по умолчанию
            совпадает с шириной отчёта в консоли.

    Returns:
        Строка ровно указанной ширины; более длинный текст не обрезается.
    """
    return text.center(width, "=")
