"""Печать готового отчёта в консоль."""


def print_report(lines: list[str]) -> None:
    """Печатает готовый отчёт в консоль построчно.

    Args:
        lines: Строки отчёта в порядке вывода.

    Note:
        Функция только печатает: расчёты и форматирование выполняются
        до вызова, в services и utils.
    """
    for line in lines:
        print(line)
