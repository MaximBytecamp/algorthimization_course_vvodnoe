/* Короткий SHA-256 от строки — тот же алгоритм, что и при генерации ключей. */
async function shortHash(text) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return Array.from(new Uint8Array(buf))
    .map(b => b.toString(16).padStart(2, '0'))
    .join('')
    .slice(0, 16);
}

/* Проверка одного вопроса: выбранные варианты должны точно совпасть с ключом. */
async function isCorrect(question, picked) {
  if (!picked || picked.length !== question.key.length) return false;
  const hashes = await Promise.all(
    picked.map(i => shortHash(`${QUIZ.salt}|${question.id}|${i}`))
  );
  return hashes.every(h => question.key.includes(h));
}

function gradeFor(score) {
  return QUIZ.grades.find(g => score >= g.min) || QUIZ.grades[QUIZ.grades.length - 1];
}
