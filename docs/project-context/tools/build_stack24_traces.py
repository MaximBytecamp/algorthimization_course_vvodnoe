"""Rebuild module 24 traces for the existing massivy/algo.js player."""
import json
from pathlib import Path
from build_queue25_traces import CodeBlocks, record

BASE = Path(__file__).resolve().parents[3] / 'op04-algoritmizaciya/lineynye/24-monotonnyy-stek'


def source(filename, name):
    parser = CodeBlocks()
    parser.feed((BASE / filename).read_text())
    block = next(x for x in parser.blocks if 'def ' + name in x)
    lines = []
    for line in block.splitlines():
        if line.startswith('>>>'):
            if lines:
                break
            lines.append(line[4:])
        elif line.startswith('...'):
            lines.append(line[4:] if len(line) > 3 else '')
        else:
            break
    return '\n'.join(lines).rstrip()


def explain(line, event, value, is_yield):
    text = line.strip()
    if event == 'return':
        return f'Вызов завершён. Результат: {value!r}.'
    if text.startswith('return '):
        return 'Сейчас возвращается итоговый ответ после прохода.'
    if text.startswith('for '):
        return 'Цикл получает следующую позицию и её значение. При исчерпании входа цикл завершится.'
    if text.startswith('while '):
        return 'Проверяется наличие вершины и сравнение её значения с текущим. При выполнении условия начинается снятие.'
    if text.startswith('answer ='):
        return 'Создаётся список ответов. Начальные значения сохранятся у позиций без подходящего элемента справа.'
    if text == 'stack = []':
        return 'Создаётся пустой стек индексов. Дно находится слева, вершина — справа.'
    if 'answer[stack.pop()]' in text:
        return 'Снимается индекс с вершины. Для этой позиции текущее value записывается как ближайшее большее справа.'
    if text.startswith('old_day ='):
        return 'С вершины снимается номер дня, для которого найдена более высокая температура.'
    if text.startswith('answer[old_day]'):
        return 'Разность day − old_day записывается как число дней до потепления.'
    if 'stack.append' in text:
        return 'Текущий индекс добавляется на вершину стека. Сохранённая позиция участвует в последующих сравнениях.'
    if text.startswith('h ='):
        return 'Снимается индекс столбца, и его высота сохраняется в h. Текущий i задаёт правую границу.'
    if text.startswith('left ='):
        return 'После снятия новая вершина задаёт левую границу. При пустом стеке используется −1.'
    if text.startswith('best = max'):
        return 'Вычисляются ширина i − left − 1 и площадь h × ширина. best сохраняет наибольшую площадь.'
    if text == 'best = 0':
        return 'Начальная максимальная площадь равна нулю.'
    return 'Сейчас выполняется подсвеченная строка. Её результат будет виден на следующем шаге.'


def build():
    cases = [
        ('stack24_greater', '01-sleduyushchiy-bolshiy.html', 'next_greater', [2, 1, 3, 2], 'nums', ['i'], [3, 3, -1, -1]),
        ('stack24_days', '02-temperatury.html', 'warmer_days', [73, 74, 74, 71, 72], 'temps', ['day'], [1, 0, 0, 1, 0]),
        ('stack24_hist', '03-gistogramma.html', 'largest_rectangle', [2, 1, 2], 'heights', ['i'], 3),
    ]
    traces = {}
    for key, filename, name, values, label, pointers, expected in cases:
        trace = record(source(filename, name), f'{name}({values!r})', values, label, pointers, explain)
        assert trace['result'] == repr(expected)
        traces[key] = trace
    payload = json.dumps(traces, ensure_ascii=False, indent=2)
    (BASE / 'traces24.js').write_text('/* Generated by docs/project-context/tools/build_stack24_traces.py. */\nwindow.TRACES = Object.assign(window.TRACES || {}, ' + payload + ');\n')
    print('Built:', ', '.join(f'{key}: {len(t["frames"])} frames' for key, t in traces.items()))
    return traces


if __name__ == '__main__':
    build()
